// Packs every prompt-writing skill in skills/ into src/skills.generated.js, so the panel can send them
// to Claude without reading files at runtime. Same skills and reference files as the Seedance
// Production connector's get_skill(name, file).
// Run after editing a skill:  node tools/build-skills.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SKILLS_DIR = join(root, "skills");

// name: [main file, folder with reference files (or null), title, what it's for]
const SKILLS = {
  cinedance: ["cinedance-prompt-builder.md", null, "CINEDANCE (Seedance Prompt Builder v4.4.2)", "Writing every final Seedance prompt, and repairing failed ones"],
  shotlist: ["shotlist-builder/SKILL.md", "shotlist-builder", "Shotlist Builder", "Breaking an episode, scene or ad shot into shots: asset list, blocking approval, micro-beats, grouping"],
  acting: ["acting-system.md", null, "Acting System", "Character master profiles, per-shot performance paragraphs, locked voice prompts"],
  lira: ["lira-image-prompts.md", null, "Lira", "Image prompts: character sheets, costumes, locations, props, first frames"],
};

const stripFrontmatter = (text) => text.replace(/^---\n[\s\S]*?\n---\n/, "").trim();

function mdFiles(dir) {
  return readdirSync(dir)
    .flatMap((name) => {
      const p = join(dir, name);
      return statSync(p).isDirectory() ? mdFiles(p) : name.endsWith(".md") ? [p] : [];
    })
    .sort();
}

const main = {};
const files = {};
const info = {};
for (const [name, [file, folder, title, purpose]] of Object.entries(SKILLS)) {
  main[name] = stripFrontmatter(readFileSync(join(SKILLS_DIR, file), "utf8"));
  files[name] = {};
  if (folder) {
    for (const p of mdFiles(join(SKILLS_DIR, folder))) {
      const rel = relative(SKILLS_DIR, p).split("\\").join("/");
      if (rel !== file) files[name][rel] = readFileSync(p, "utf8").trim();
    }
  }
  info[name] = { title, purpose, main: file, files: Object.keys(files[name]) };
}
const guide = readFileSync(join(SKILLS_DIR, "connector-guide.md"), "utf8").trim();

const out =
  "/* Generated by tools/build-skills.mjs from skills/. Edit the .md files, not this one. */\n" +
  "window.Studio = window.Studio || {};\n" +
  "window.Studio.SKILLS = " + JSON.stringify(main) + ";\n" +
  "window.Studio.SKILL_FILES = " + JSON.stringify(files) + ";\n" +
  "window.Studio.SKILL_INFO = " + JSON.stringify(info) + ";\n" +
  "window.Studio.CONNECTOR_GUIDE = " + JSON.stringify(guide) + ";\n";

writeFileSync(join(root, "src/skills.generated.js"), out);
console.log(
  "Wrote src/skills.generated.js",
  Object.entries(main).map(([k, v]) => `${k}: ${v.length} chars + ${Object.keys(files[k]).length} reference files`).join(", ")
);
