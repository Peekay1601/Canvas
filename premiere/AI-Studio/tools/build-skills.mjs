// Packs the prompt-writing skills in skills/*.md into src/skills.generated.js,
// so the panel can send them to Claude without reading files at runtime.
// Run after editing a skill:  node tools/build-skills.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SKILLS = {
  lira: "skills/lira-image-prompts.md",
  cinedance: "skills/cinedance-prompt-builder.md",
  shotlist: "skills/shotlist-builder.md",
  acting: "skills/acting-system.md",
};

const stripFrontmatter = (text) => text.replace(/^---\n[\s\S]*?\n---\n/, "").trim();

const packed = Object.fromEntries(
  Object.entries(SKILLS).map(([name, file]) => [name, stripFrontmatter(readFileSync(join(root, file), "utf8"))])
);

const out =
  "/* Generated by tools/build-skills.mjs from skills/*.md. Edit the .md files, not this one. */\n" +
  "window.Studio = window.Studio || {};\n" +
  "window.Studio.SKILLS = " + JSON.stringify(packed, null, 0) + ";\n";

writeFileSync(join(root, "src/skills.generated.js"), out);
console.log("Wrote src/skills.generated.js", Object.entries(packed).map(([k, v]) => `${k}: ${v.length} chars`).join(", "));
